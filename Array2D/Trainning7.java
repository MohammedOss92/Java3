
public class Trainning7 {

    public static void main(String[] args) {

        // إنشاء مصفوفة ثنائية الأبعاد
        int[][] numbers = {
            {10, 20, 30},
            {40, 50, 60},
            {70, 80, 90}
        };

        // المرور على الصفوف
        for (int i = 0; i < numbers.length; i++) {

            // المرور على الأعمدة داخل كل صف
            for (int j = 0; j < numbers[i].length; j++) {

                // أخذ العنصر الحالي من المصفوفة
                int num = numbers[i][j];

                // متغير لتخزين الرقم بعد عكسه
                // نبدأ من صفر لكل عنصر جديد
                int reversed = 0;

                // نستمر ما دام الرقم أكبر من صفر
                while (num > 0) {

                    // استخراج آخر رقم
                    int digit = num % 10;

                    // إضافة الرقم المستخرج إلى الرقم المعكوس
                    reversed = reversed * 10 + digit;

                    // حذف آخر رقم من العدد الأصلي
                    num = num / 10;
                }

                // طباعة الرقم المعكوس بخانتين
                // %02d تجعل 1 تظهر 01 و 2 تظهر 02
                System.out.printf("%02d ", reversed);
            }

            // الانتقال إلى سطر جديد بعد انتهاء كل صف
            System.out.println();
        }
    }
}
