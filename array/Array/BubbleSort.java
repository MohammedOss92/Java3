
public class BubbleSort {

    public static void main(String[] args) {

        // إنشاء Array تحتوي على أرقام غير مرتبة
        int[] num = {5, 2, 8, 1, 3};

        // الحلقة الخارجية: تكرار عملية الترتيب
        for (int i = 0; i < num.length - 1; i++) {

            // الحلقة الداخلية: مقارنة العناصر المتجاورة
            for (int j = 0; j < num.length - 1; j++) {

                // إذا كان العنصر الحالي أكبر من العنصر التالي
                if (num[j] > num[j + 1]) {

                    // حفظ قيمة العنصر الحالي مؤقتًا حتى لا نفقدها
                    int temp = num[j];

                    // وضع قيمة العنصر التالي في مكان العنصر الحالي
                    num[j] = num[j + 1];

                    // وضع القيمة المحفوظة في مكان العنصر التالي
                    num[j + 1] = temp;
                }
            }
        }

        // طباعة المصفوفة بعد ترتيبها
        for (int i = 0; i < num.length; i++) {

            // طباعة العنصر الحالي
            System.out.print(num[i] + " ");
        }
    }
}
