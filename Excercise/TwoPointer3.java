public class TwoPointer3 {

    public static void main(String[] args) {

        int[] numbers = {2, 4, 4, 4, 8, 8, 10,8};

        int left = 0;
        int right = left + 1;

        while (right < numbers.length) {

            if (numbers[left] == numbers[right]
                    && (left == 0 || numbers[left] != numbers[left - 1])) {

                int count = 0;

                for (int i = 0; i < numbers.length; i++) {

                    if (numbers[i] == numbers[left]) {
                        count++;
                    }
                }

                System.out.println(
                    "الرقم " + numbers[left] + " تكرر " + count + " مرات"
                );
            }

            left++;
            right++;
        }
    }
}

