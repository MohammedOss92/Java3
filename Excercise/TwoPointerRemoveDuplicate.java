public class TwoPointerRemoveDuplicate {

    public static void main(String[] args) {

        int[] num = {2, 2, 4, 4, 4, 6, 8, 8, 10};

        int i = 1;
        int j = 0;

        while (i < num.length) {

            if (num[i] != num[j]) {

                j++;
                num[j] = num[i];

            }

            i++;
        }

        int uniqueCount = j + 1;

        for (int k = 0; k < uniqueCount; k++) {
            System.out.print(num[k] + " ");
        }

    }
}

