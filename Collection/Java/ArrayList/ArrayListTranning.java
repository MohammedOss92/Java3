
import java.util.ArrayList; // استيراد ArrayList
import java.util.Collections; // استيراد دوال الترتيب والعكس
import java.util.Iterator; // استيراد Iterator

public class ArrayListTranning { // بداية الكلاس

    public static void main(String[] args) { // بداية الدالة الرئيسية

        // =================================
        // 1. إنشاء ArrayList
        // =================================

        ArrayList<Integer> numbers = new ArrayList<>(); // إنشاء قائمة لتخزين أعداد صحيحة

        // =================================
        // 2. إضافة العناصر add()
        // =================================

        numbers.add(10); // إضافة 10
        numbers.add(20); // إضافة 20
        numbers.add(30); // إضافة 30
        numbers.add(40); // إضافة 40
        numbers.add(50); // إضافة 50

        System.out.println("Original List: " + numbers); // طباعة القائمة الأصلية

        // =================================
        // 3. إضافة عنصر في موقع محدد add(index, value)
        // =================================

        numbers.add(2, 25); // إضافة 25 في index رقم 2

        System.out.println("After add: " + numbers); // طباعة القائمة بعد الإضافة

        // =================================
        // 4. معرفة عدد العناصر size()
        // =================================

        System.out.println("Size: " + numbers.size()); // طباعة عدد العناصر

        // =================================
        // 5. جلب عنصر get()
        // =================================

        System.out.println("Element at index 2: " + numbers.get(2)); // جلب العنصر في index 2

        // =================================
        // 6. تعديل عنصر set()
        // =================================

        numbers.set(2, 100); // تعديل العنصر في index 2 ليصبح 100

        System.out.println("After set: " + numbers); // طباعة القائمة بعد التعديل

        // =================================
        // 7. البحث عن قيمة contains()
        // =================================

        boolean exists = numbers.contains(30); // فحص هل القيمة 30 موجودة

        System.out.println("Contains 30: " + exists); // طباعة نتيجة البحث

        // =================================
        // 8. معرفة موقع العنصر indexOf()
        // =================================

        int index = numbers.indexOf(40); // البحث عن موقع القيمة 40

        System.out.println("Index of 40: " + index); // طباعة الموقع أو -1 إذا لم توجد

        // =================================
        // 9. معرفة موقع آخر ظهور lastIndexOf()
        // =================================

        numbers.add(20); // إضافة 20 مرة أخرى

        System.out.println("Last index of 20: " + numbers.lastIndexOf(20)); // آخر موقع للقيمة 20

        // =================================
        // 10. التحقق هل القائمة فارغة isEmpty()
        // =================================

        System.out.println("Is Empty: " + numbers.isEmpty()); // فحص هل القائمة فارغة

        // =================================
        // 11. المرور باستخدام for
        // =================================

        System.out.println("Using for:");

        for (int i = 0; i < numbers.size(); i++) { // المرور على جميع المواقع
            System.out.println(numbers.get(i)); // جلب وطباعة العنصر الحالي
        }

        // =================================
        // 12. المرور باستخدام for-each
        // =================================

        System.out.println("Using for-each:");

        for (int number : numbers) { // أخذ قيمة كل عنصر مباشرة
            System.out.println(number); // طباعة العنصر
        }

        // =================================
        // 13. حساب مجموع العناصر
        // =================================

        int sum = 0; // متغير لتجميع القيم

        for (int number : numbers) { // المرور على العناصر
            sum += number; // إضافة القيمة الحالية إلى المجموع
        }

        System.out.println("Sum: " + sum); // طباعة المجموع

        // =================================
        // 14. إيجاد أكبر عنصر
        // =================================

        int max = numbers.get(0); // افتراض أن أول عنصر هو الأكبر

        for (int number : numbers) { // المرور على جميع العناصر
            if (number > max) { // مقارنة العنصر الحالي بالأكبر
                max = number; // تحديث الأكبر إذا وجدنا قيمة أكبر
            }
        }

        System.out.println("Max: " + max); // طباعة أكبر قيمة

        // =================================
        // 15. إيجاد أصغر عنصر
        // =================================

        int min = numbers.get(0); // افتراض أن أول عنصر هو الأصغر

        for (int number : numbers) { // المرور على جميع العناصر
            if (number < min) { // مقارنة العنصر الحالي بالأصغر
                min = number; // تحديث الأصغر إذا وجدنا قيمة أصغر
            }
        }

        System.out.println("Min: " + min); // طباعة أصغر قيمة

        // =================================
        // 16. حذف حسب Index remove(index)
        // =================================

        numbers.remove(0); // حذف العنصر الموجود في index رقم 0

        System.out.println("After remove index: " + numbers); // طباعة القائمة

        // =================================
        // 17. حذف حسب القيمة remove(value)
        // =================================

        numbers.remove(Integer.valueOf(30)); // حذف القيمة 30 نفسها

        System.out.println("After remove value: " + numbers); // طباعة القائمة

        // =================================
        // 18. ترتيب تصاعدي sort()
        // =================================

        Collections.sort(numbers); // ترتيب القائمة من الأصغر إلى الأكبر

        System.out.println("Ascending: " + numbers); // طباعة القائمة تصاعديًا

        // =================================
        // 19. ترتيب تنازلي reverseOrder()
        // =================================

        Collections.sort(numbers, Collections.reverseOrder()); // ترتيب القائمة من الأكبر إلى الأصغر

        System.out.println("Descending: " + numbers); // طباعة القائمة تنازليًا

        // =================================
        // 20. عكس الترتيب الحالي reverse()
        // =================================

        Collections.reverse(numbers); // عكس ترتيب العناصر الحالي

        System.out.println("Reversed: " + numbers); // طباعة القائمة بعد العكس

        // =================================
        // 21. البحث باستخدام Linear Search
        // =================================

        int target = 40; // القيمة التي نريد البحث عنها

        boolean found = false; // متغير لمعرفة هل وجدنا القيمة

        for (int i = 0; i < numbers.size(); i++) { // المرور على القائمة

            if (numbers.get(i) == target) { // مقارنة قيمة العنصر بالقيمة المطلوبة

                found = true; // تسجيل أن العنصر موجود

                System.out.println("Found at index: " + i); // طباعة موقع العنصر

                break; // الخروج من الحلقة بعد العثور عليه
            }
        }

        if (!found) { // فحص هل لم نجد العنصر
            System.out.println("Not Found"); // طباعة أنه غير موجود
        }

        // =================================
        // 22. استخدام Iterator
        // =================================

        Iterator<Integer> iterator = numbers.iterator(); // إنشاء Iterator للتنقل بين العناصر

        while (iterator.hasNext()) { // فحص هل يوجد عنصر آخر
            int value = iterator.next(); // جلب العنصر التالي
            System.out.println(value); // طباعة العنصر
        }

        // =================================
        // 23. إضافة مجموعة أخرى addAll()
        // =================================

        ArrayList<Integer> extraNumbers = new ArrayList<>(); // إنشاء قائمة إضافية

        extraNumbers.add(60); // إضافة 60
        extraNumbers.add(70); // إضافة 70

        numbers.addAll(extraNumbers); // إضافة جميع عناصر القائمة الثانية إلى الأولى

        System.out.println("After addAll: " + numbers); // طباعة القائمة

        // =================================
        // 24. الاحتفاظ بالعناصر المشتركة retainAll()
        // =================================

        ArrayList<Integer> selected = new ArrayList<>(); // إنشاء قائمة للاحتفاظ بعناصر محددة

        selected.add(40); // إضافة 40
        selected.add(60); // إضافة 60

        numbers.retainAll(selected); // الاحتفاظ فقط بالعناصر الموجودة في selected

        System.out.println("After retainAll: " + numbers); // طباعة العناصر المشتركة

        // =================================
        // 25. حذف مجموعة من العناصر removeAll()
        // =================================

        numbers.removeAll(selected); // حذف جميع العناصر الموجودة في selected

        System.out.println("After removeAll: " + numbers); // طباعة القائمة بعد الحذف

        // =================================
        // 26. تحويل القائمة إلى Array toArray()
        // =================================

        Integer[] array = numbers.toArray(new Integer[0]); // تحويل ArrayList إلى مصفوفة

        System.out.println("Array length: " + array.length); // طباعة طول المصفوفة

        // =================================
        // 27. حذف جميع العناصر clear()
        // =================================

        numbers.clear(); // حذف جميع عناصر القائمة

        System.out.println("After clear: " + numbers); // طباعة القائمة الفارغة

        // =================================
        // 28. فحص هل القائمة فارغة
        // =================================

        System.out.println("Is Empty: " + numbers.isEmpty()); // ستكون النتيجة true

    } // نهاية main

} // نهاية الكلاس






