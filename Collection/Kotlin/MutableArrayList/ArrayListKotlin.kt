
fun main() { // بداية الدالة الرئيسية

    // =====================================
    // 1. إنشاء MutableList
    // =====================================

    val nums = mutableListOf<Int>() // إنشاء قائمة أعداد صحيحة قابلة للتعديل

    nums.add(10) // إضافة الرقم 10
    nums.add(20) // إضافة الرقم 20
    nums.add(30) // إضافة الرقم 30

    println(nums) // طباعة القائمة

    // =====================================
    // 2. إضافة عنصر في موقع محدد
    // =====================================

    nums.add(2, 5) // إضافة الرقم 5 في الموقع 2
    println(nums) // طباعة القائمة بعد الإضافة

    // =====================================
    // 3. الوصول إلى العناصر وتعديلها
    // =====================================

    println(nums.get(2)) // جلب العنصر الموجود في الموقع 2 وطباعته

    nums.set(0, 55) // تغيير العنصر الموجود في الموقع 0 إلى 55

    println(nums.size) // طباعة عدد عناصر القائمة

    println(nums) // طباعة القائمة بعد التعديل

    // =====================================
    // 4. فحص العناصر والبحث عن مواقعها
    // =====================================

    println(nums.contains(100)) // فحص هل الرقم 100 موجود

    println(nums.indexOf(55)) // إرجاع موقع أول ظهور للرقم 55

    println(nums.lastIndexOf(55)) // إرجاع موقع آخر ظهور للرقم 55

    println(nums.isEmpty()) // فحص هل القائمة فارغة

    // =====================================
    // 5. الطباعة باستخدام for
    // =====================================

    for (i in 0 until nums.size) { // المرور على مواقع القائمة من 0 حتى قبل size

        println(nums[i]) // جلب قيمة العنصر حسب الموقع وطباعتها
    }

    // =====================================
    // 6. الطباعة باستخدام for-each
    // =====================================

    for (n in nums) { // المرور على جميع عناصر القائمة مباشرة

        println(n) // طباعة قيمة العنصر الحالي
    }

    // =====================================
    // 7. حساب المجموع باستخدام for-each
    // =====================================

    var sum = 0 // متغير لتخزين مجموع العناصر ويبدأ من صفر

    for (i in nums) { // المرور على قيم العناصر مباشرة

        sum += i // إضافة قيمة العنصر الحالي إلى المجموع
    }

    println(sum) // طباعة مجموع العناصر

    // =====================================
    // 8. حساب المجموع باستخدام for
    // =====================================

    var sum2 = 0 // متغير آخر لتخزين المجموع

    for (i in 0 until nums.size) { // المرور على مواقع العناصر

        sum2 += nums[i] // إضافة قيمة العنصر الموجود في الموقع i
    }

    println(sum2) // طباعة المجموع الثاني

    // =====================================
    // 9. إيجاد أكبر وأصغر عنصر
    // =====================================

    var max = nums[0] // افتراض أن أول عنصر هو الأكبر

    var min = nums[0] // افتراض أن أول عنصر هو الأصغر

    for (i in 0 until nums.size) { // المرور على جميع مواقع العناصر

        if (nums[i] > max) { // فحص هل العنصر الحالي أكبر من الأكبر

            max = nums[i] // تحديث قيمة الأكبر
        }
    }

    for (i in nums) { // المرور على قيم العناصر مباشرة

        if (i < min) { // فحص هل العنصر الحالي أصغر من الأصغر

            min = i // تحديث قيمة الأصغر
        }
    }

    println("Max: $max") // طباعة أكبر عنصر

    println("Min: $min") // طباعة أصغر عنصر

    // =====================================
    // 10. الحذف
    // =====================================

    nums.removeAt(1) // حذف العنصر الموجود في الموقع 1

    nums.remove(40) // حذف القيمة 40 إذا كانت موجودة

    println(nums) // طباعة القائمة بعد الحذف

    // =====================================
    // 11. الترتيب Sorting
    // =====================================

    nums.sort() // ترتيب العناصر تصاعديًا من الأصغر إلى الأكبر

    println("Ascending: $nums") // طباعة القائمة تصاعديًا

    nums.sortDescending() // ترتيب العناصر تنازليًا من الأكبر إلى الأصغر

    println("Descending: $nums") // طباعة القائمة تنازليًا

    nums.reverse() // عكس الترتيب الحالي للقائمة

    println("Reverse: $nums") // طباعة القائمة بعد العكس

    // =====================================
    // 12. البحث الخطي Linear Search
    // =====================================

    val target = 40 // القيمة التي نريد البحث عنها

    var found = false // متغير لمعرفة هل وجدنا العنصر

    for (i in 0 until nums.size) { // المرور على جميع مواقع القائمة

        if (nums[i] == target) { // مقارنة قيمة العنصر بالقيمة المطلوبة

            found = true // تسجيل أن العنصر موجود

            println("Found at index: $i") // طباعة موقع العنصر

            break // إيقاف الحلقة بعد العثور على العنصر
        }
    }

    if (!found) { // فحص هل لم يتم العثور على العنصر

        println("Not Found") // طباعة رسالة عدم العثور عليه
    }

    // =====================================
    // 13. استخدام Iterator
    // =====================================

    val iterator = nums.iterator() // إنشاء Iterator للمرور على عناصر القائمة

    while (iterator.hasNext()) { // الاستمرار طالما يوجد عنصر قادم

        val value = iterator.next() // جلب العنصر التالي

        if (value < 30) { // فحص هل قيمة العنصر أصغر من 30

            iterator.remove() // حذف العنصر الحالي بأمان
        }
    }

    println("After Iterator: $nums") // طباعة القائمة بعد حذف الأرقام الأصغر من 30

    // =====================================
    // 14. نهاية البرنامج
    // =====================================

} // نهاية الدالة الرئيسية
