
fun main() {

    // ==================================
    // 1. إنشاء HashSet وإضافة العناصر
    // ==================================

    val nums = HashSet<Int>() // إنشاء مجموعة أعداد صحيحة

    nums.add(30) // إضافة 30
    nums.add(10) // إضافة 10
    nums.add(20) // إضافة 20
    nums.add(10) // لن تضاف لأنها مكررة
    nums.add(40) // إضافة 40

    println(nums) // طباعة المجموعة (الترتيب غير مضمون)

    // ==================================
    // 2. البحث عن عنصر
    // ==================================

    println(nums.contains(20)) // هل 20 موجودة؟ true

    // ==================================
    // 3. حذف عنصر
    // ==================================

    println(nums.remove(10)) // حذف 10 وإرجاع true إذا نجح الحذف

    // ==================================
    // 4. عدد العناصر والتحقق من الفراغ
    // ==================================

    println(nums.size) // طباعة عدد العناصر
    println(nums.isEmpty()) // هل المجموعة فارغة؟

    // ==================================
    // 5. المرور باستخدام for-each
    // ==================================

    for (num in nums) { // المرور على جميع العناصر
        println(num) // طباعة العنصر الحالي
    }

    println("________")

    // ==================================
    // 6. المرور باستخدام Iterator
    // ==================================

    val it = nums.iterator() // إنشاء Iterator

    while (it.hasNext()) { // التأكد من وجود عنصر قادم

        val num = it.next() // جلب العنصر الحالي

        println(num) // طباعة العنصر

        if (num > 20) { // إذا كان العنصر أكبر من 20
            it.remove() // حذف العنصر الحالي بأمان
        }
    }

    println(nums) // طباعة العناصر المتبقية

    // ==================================
    // 7. إنشاء مجموعتين جديدتين
    // ==================================

    val nums1 = hashSetOf(10, 20, 30) // المجموعة الأولى
    val nums2 = hashSetOf(30, 40, 50) // المجموعة الثانية

    // ==================================
    // 8. addAll
    // ==================================

    nums1.addAll(nums2) // إضافة عناصر nums2 إلى nums1 دون تكرار

    println(nums1) // تحتوي على 10 و20 و30 و40 و50

    // ==================================
    // 9. retainAll
    // ==================================

    nums1.retainAll(nums2) // الاحتفاظ بالعناصر المشتركة فقط

    println(nums1) // تحتوي على 30 و40 و50

    // ==================================
    // 10. removeAll
    // ==================================

    nums1.removeAll(nums2) // حذف عناصر nums2 من nums1

    println(nums1) // مجموعة فارغة

    // ==================================
    // 11. containsAll
    // ==================================

    val nums3 = hashSetOf(10, 20, 30, 40) // المجموعة الأولى
    val nums4 = hashSetOf(20, 30) // المجموعة الثانية

    println(nums3.containsAll(nums4)) // true لأن كل عناصر nums4 موجودة

    val nums5 = hashSetOf(20, 50) // مجموعة تحتوي على عنصر غير موجود

    println(nums3.containsAll(nums5)) // false لأن 50 غير موجودة

    // ==================================
    // 12. التحويل إلى Array
    // ==================================

    val numsArray = hashSetOf(30, 10, 20) // إنشاء HashSet

    val arr = numsArray.toTypedArray() // تحويل HashSet إلى Array

    println(arr.contentToString()) // طباعة محتويات المصفوفة

    println(arr[0]) // الوصول إلى أول عنصر باستخدام index

    // ==================================
    // 13. التحويل إلى List
    // ==================================

    val numsList1 = hashSetOf(30, 10, 20) // إنشاء HashSet

    val list = numsList1.toList() // تحويل HashSet إلى List

    println(numsList1) // المجموعة الأصلية كما هي

    println(list) // طباعة القائمة الجديدة

    // ==================================
    // 14. التحويل إلى MutableList
    // ==================================

    val numsList2 = hashSetOf(30, 10, 20) // إنشاء HashSet

    val mutableList = numsList2.toMutableList() // تحويل إلى قائمة قابلة للتعديل

    mutableList.add(40) // إضافة 40 إلى القائمة الجديدة فقط

    mutableList.remove(20) // حذف 20 من القائمة الجديدة فقط

    println(numsList2) // المجموعة الأصلية لم تتغير

    println(mutableList) // القائمة الجديدة بعد الإضافة والحذف

    // ==================================
    // 15. clear
    // ==================================

    nums.clear() // حذف جميع عناصر المجموعة الأصلية nums

    println(nums) // طباعة مجموعة فارغة
    println(nums.isEmpty()) // true لأن المجموعة أصبحت فارغة
}
