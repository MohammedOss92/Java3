
fun main() {

    // =========================================
    // 1. إنشاء LinkedHashSet وإضافة العناصر
    // =========================================

    val nums = LinkedHashSet<Int>() // إنشاء مجموعة أعداد صحيحة

    nums.add(50) // إضافة 50
    nums.add(20) // إضافة 20
    nums.add(40) // إضافة 40
    nums.add(10) // إضافة 10
    nums.add(20) // لن تضاف لأنها مكررة

    println(nums) // [50, 20, 40, 10] ترتيب الإدخال محفوظ

    // =========================================
    // 2. البحث عن عنصر
    // =========================================

    println(nums.contains(40)) // true إذا كان 40 موجودًا

    // =========================================
    // 3. حذف عنصر
    // =========================================

    println(nums.remove(20)) // حذف 20 وإرجاع true إذا نجح الحذف

    println(nums) // [50, 40, 10]

    // =========================================
    // 4. عدد العناصر والتحقق من الفراغ
    // =========================================

    println(nums.size) // عدد العناصر = 3

    println(nums.isEmpty()) // false لأن المجموعة ليست فارغة

    // =========================================
    // 5. المرور باستخدام for-each
    // =========================================

    for (num in nums) { // المرور على جميع العناصر حسب ترتيب الإدخال

        println(num) // طباعة العنصر الحالي
    }

    // =========================================
    // 6. حذف عنصر وإعادة إضافته
    // =========================================

    val nums2 = linkedSetOf(10, 20, 30) // إنشاء مجموعة جديدة

    nums2.remove(20) // حذف 20

    nums2.add(20) // إعادة إضافة 20 إلى نهاية الترتيب

    println(nums2) // [10, 30, 20]

    // =========================================
    // 7. المرور باستخدام Iterator
    // =========================================

    val it = nums.iterator() // إنشاء Iterator للمجموعة

    while (it.hasNext()) { // التأكد من وجود عنصر قادم

        val num = it.next() // جلب العنصر الحالي

        println(num) // طباعة العنصر

        if (num > 30) { // إذا كان العنصر أكبر من 30

            it.remove() // حذف العنصر الحالي بأمان
        }
    }

    println(nums) // [10] بعد حذف 50 و40

    // =========================================
    // 8. إنشاء مجموعتين
    // =========================================

    val nums3 = linkedSetOf(10, 20, 30) // المجموعة الأولى

    val nums4 = linkedSetOf(30, 40, 50) // المجموعة الثانية

    // =========================================
    // 9. addAll
    // =========================================

    nums3.addAll(nums4) // إضافة عناصر nums4 إلى nums3 دون تكرار

    println(nums3) // [10, 20, 30, 40, 50]

    // =========================================
    // 10. retainAll
    // =========================================

    val nums5 = linkedSetOf(10, 20, 30) // المجموعة الأولى

    val nums6 = linkedSetOf(30, 40, 50) // المجموعة الثانية

    nums5.retainAll(nums6) // الاحتفاظ بالعناصر المشتركة فقط

    println(nums5) // [30]

    // =========================================
    // 11. removeAll
    // =========================================

    val nums7 = linkedSetOf(10, 20, 30, 40) // المجموعة الأولى

    val nums8 = linkedSetOf(20, 40) // المجموعة الثانية

    nums7.removeAll(nums8) // حذف عناصر nums8 من nums7

    println(nums7) // [10, 30]

    // =========================================
    // 12. containsAll
    // =========================================

    val nums9 = linkedSetOf(10, 20, 30, 40) // المجموعة الأولى

    val nums10 = linkedSetOf(20, 30) // المجموعة الثانية

    println(nums9.containsAll(nums10)) // true لأن جميع عناصر nums10 موجودة

    // =========================================
    // 13. clear
    // =========================================

    nums9.clear() // حذف جميع عناصر nums9

    println(nums9) // []

    println(nums9.isEmpty()) // true لأن المجموعة أصبحت فارغة
}
