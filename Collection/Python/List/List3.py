
# إنشاء قائمة تحتوي على أربعة أرقام
nums = [40, 10, 30, 20]

# ترتيب القائمة تصاعدياً
nums.sort()

# طباعة القائمة
print(nums)  # [10, 20, 30, 40]

# ترتيب القائمة تنازلياً
nums.sort(reverse=True)

# طباعة القائمة
print(nums)  # [40, 30, 20, 10]

# عكس ترتيب القائمة الحالي
nums.reverse()

# طباعة القائمة
print(nums)  # [10, 20, 30, 40]

# حذف جميع العناصر
nums.clear()

# طباعة القائمة
print(nums)  # []
nums = [40, 10, 30, 20]

new_nums = sorted(nums)

print(new_nums)  # [10, 20, 30, 40]
print(nums)      # [40, 10, 30, 20]

nums = [10, 20, 30]

nums.extend([40, 50])

print(nums)
# [10, 20, 30, 40, 50]

nums = [10, 20, 30]

nums.append([40, 50])

print(nums)
