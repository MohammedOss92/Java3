
nums = [10, 20, 30, 20, 40, 20]

# طباعة القائمة
print(nums)

# حساب عدد مرات ظهور الرقم 20 وطباعته
print(nums.count(20))

# حذف أول ظهور للرقم 20
nums.remove(20)

# طباعة القائمة بعد الحذف
print(nums)

# حذف العنصر الموجود في الموقع 2 وطباعته
print(nums.pop(2))

# طباعة القائمة بعد الحذف
print(nums)
