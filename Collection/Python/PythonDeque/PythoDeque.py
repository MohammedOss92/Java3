
from collections import deque

# =================================
# 1. إنشاء deque
# =================================

nums = deque([10, 20, 30, 40, 50])

# إنشاء deque فارغة
empty = deque()


# =================================
# 2. الإضافة Add
# =================================

nums.append(60)          # إضافة عنصر في النهاية
nums.appendleft(5)       # إضافة عنصر في البداية

nums.extend([70, 80])    # إضافة مجموعة في النهاية
nums.extendleft([1, 2])  # إضافة مجموعة في البداية (بترتيب عكسي)


# =================================
# 3. الحذف Remove
# =================================

nums.pop()               # حذف آخر عنصر
nums.popleft()           # حذف أول عنصر

nums.remove(30)          # حذف أول ظهور للقيمة 30

del nums[2]              # حذف العنصر الموجود عند index 2

# nums.clear()           # حذف جميع العناصر


# =================================
# 4. الوصول إلى العناصر Access
# =================================

first = nums[0]          # الوصول إلى أول عنصر
last = nums[-1]          # الوصول إلى آخر عنصر
item = nums[2]           # الوصول إلى العنصر عند index 2

print(first)
print(last)
print(item)


# =================================
# 5. تعديل العناصر Update
# =================================

nums[0] = 100            # تعديل أول عنصر
nums[-1] = 500           # تعديل آخر عنصر
nums[2] = 300            # تعديل العنصر عند index 2


# =================================
# 6. البحث والفحص Search
# =================================

print(30 in nums)        # التحقق من وجود 30

print(nums.index(40))    # إرجاع index للقيمة 40
print(nums.count(20))    # حساب عدد مرات ظهور 20

print(len(nums))         # عدد العناصر
print(not nums)          # التحقق هل deque فارغة

# التحقق من أنها غير فارغة
print(bool(nums))


# =================================
# 7. التكرار Loops
# =================================

# المرور على العناصر باستخدام for
for num in nums:
    print(num)

# المرور باستخدام index
for i in range(len(nums)):
    print(i, nums[i])


# =================================
# 8. المجموع والأكبر والأصغر
# =================================

total = 0                # متغير المجموع

maximum = nums[0]       # افتراض أن أول عنصر هو الأكبر
minimum = nums[0]       # افتراض أن أول عنصر هو الأصغر

for num in nums:

    total += num         # جمع العناصر

    if num > maximum:
        maximum = num    # تحديث الأكبر

    if num < minimum:
        minimum = num    # تحديث الأصغر

print("Sum:", total)
print("Max:", maximum)
print("Min:", minimum)

# الدوال الجاهزة
print(sum(nums))         # مجموع العناصر
print(max(nums))         # أكبر عنصر
print(min(nums))         # أصغر عنصر


# =================================
# 9. العكس والتدوير
# =================================

nums.reverse()           # عكس ترتيب العناصر

nums.rotate(1)           # تدوير عنصر واحد إلى اليمين
nums.rotate(-1)          # تدوير عنصر واحد إلى اليسار
nums.rotate(2)           # تدوير عنصرين إلى اليمين


# =================================
# 10. Iterator
# =================================

iterator = iter(nums)    # إنشاء Iterator

while True:
    try:
        num = next(iterator)  # جلب العنصر التالي
        print(num)
    except StopIteration:
        break


# =================================
# 11. نسخ deque
# =================================

copy_nums = nums.copy()  # إنشاء نسخة مستقلة


# =================================
# 12. maxlen
# =================================

limited = deque([10, 20, 30], maxlen=3)

limited.append(40)       # حذف 10 تلقائياً وإضافة 40

print(limited)
print(limited.maxlen)    # الحد الأقصى للعناصر


# =================================
# 13. معلومات إضافية
# =================================

print(nums)
print(nums.maxlen)       # None إذا لم يحدد maxlen
print(nums.__sizeof__()) # حجم الذاكرة التقريبي للكائن بالبايت
